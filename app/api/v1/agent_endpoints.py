def _serve(path: Path, media_type: str) -> FileResponse:
    if not path.is_file():
        # Shipped in the image, so absence is a packaging fault, not a 404 the
        # caller can do anything about — but it must not surface as a 500.
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=f"{path.name} is missing from this deployment.",
        )
    return FileResponse(path, media_type=media_type)


# GET and HEAD on all of these. Crawlers and agents probe with HEAD to check a
# document exists and what type it is before fetching it, and the StaticFiles
# mount at "/" answers 404 for any method the API routes decline — so without
# HEAD declared, a probing agent is told the manifest does not exist and stops
# discovering. These are out of the schema already, so the two methods cannot
# collide on an operation_id the way a documented route's would.
@router.api_route("/llms.txt", methods=["GET", "HEAD"], include_in_schema=False)
async def llms_txt() -> FileResponse:
    """The llms.txt manifest. text/plain so an agent does not have to sniff it."""
    return _serve(LLMS_TXT, "text/plain; charset=utf-8")


@router.api_route("/agent-guide", methods=["GET", "HEAD"], include_in_schema=False)
async def agent_guide() -> FileResponse:
    """The long-form guide, as markdown rather than a rendered page."""
    return _serve(AGENT_GUIDE, "text/markdown; charset=utf-8")


@router.head("/v1/agent/info", include_in_schema=False)
async def agent_info_head() -> AgentInfoResponse:
    """Hidden twin of the GET, for the same probing reason."""
    return await agent_info()
