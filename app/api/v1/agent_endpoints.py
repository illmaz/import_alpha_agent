"""Agent discovery. Public, unauthenticated, machine-parseable.

An autonomous buyer arrives knowing nothing. It needs, in this order: what this
service sells, how to call it, how to pay, and what comes back. That is
`/llms.txt` (the map), `/agent-guide` (the prose), `/openapi.json` (the
contract, generated by FastAPI from the code) and `/v1/agent/info` (the live
payment parameters).

Payment values are served here rather than baked into the static files because
a wallet address and a price change; a checked-in copy of them would go stale
silently and send an agent's USDC to the wrong address. `/v1/agent/info`
deliberately mirrors the vocabulary of the 402 challenge in
`x402_middleware.payment_required_response`, so discovery and rejection speak
the same language.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List, Optional

from fastapi import APIRouter, HTTPException, status
from fastapi.responses import FileResponse
from pydantic import BaseModel, ConfigDict, Field

from app.services import x402
from app.services.agent_offer import payment_terms
from app.services.x402_middleware import CREDIT_PRICE_BASE_UNITS, PAYMENT_HEADER

router = APIRouter(tags=["agent-discovery"])

PUBLIC_DIR = Path(__file__).resolve().parents[3] / "public"

LLMS_TXT = PUBLIC_DIR / "llms.txt"
AGENT_GUIDE = PUBLIC_DIR / "agent-guide.md"


class NetworkInfo(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: str
    usdc_contract: str
    is_testnet: bool
    accepted: bool = Field(
        description="False means a payment on this network will be refused."
    )
    note: Optional[str] = None


class AgentInfoResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    service: str
    description: str
    docs: Dict[str, str]
    auth_methods: List[Dict[str, Any]]
    payment: Dict[str, Any]
    networks: List[NetworkInfo]
    endpoints: List[Dict[str, str]]


def _networks() -> List[NetworkInfo]:
    """Every network we know, each saying plainly whether it is accepted.

    base-mainnet is listed because an agent will otherwise ask, and answering
    "unknown network" would be misleading — we know it, we refuse it.
    `x402.assert_testnet` turns a mainnet payment into an error, and AGENTS.md
    forbids mainnet custody. Advertising it as supported would take real USDC
    for a call that then fails.
    """
    out = []
    for name, network in sorted(x402.NETWORKS.items()):
        accepted = network.is_testnet
        out.append(
            NetworkInfo(
                name=name,
                usdc_contract=network.usdc_contract,
                is_testnet=network.is_testnet,
                accepted=accepted,
                note=(
                    None
                    if accepted
                    else "Known but NOT accepted: this deployment is testnet only. "
                    "A payment on this network will be refused and not refunded "
                    "by us. Do not send funds here."
                ),
            )
        )
    return out


def _payment_block() -> Dict[str, Any]:
    """Live payment parameters, shaped like the 402 challenge's `accepts` entry.

    Lives in app/services/agent_offer.py so the outreach drafts attach the
    identical terms rather than restating them.
    """
    return payment_terms()


